import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';
import assert from 'node:assert/strict';
import { networkLabel, deviceLabel } from './visit-labels.js';
async function moduleAt(file) { const { code } = await transform(await readFile(file, 'utf8'), { loader: 'ts', format: 'esm' }); return import('data:text/javascript;base64,' + Buffer.from(code).toString('base64')); }
const { classifyDevice } = await moduleAt('../supabase/functions/collect-visit/device.ts');
const { ipNumber, parseRanges, contains, fetchLists, classifyNetwork, enrichNetworks } = await moduleAt('../supabase/functions/visit-report/network.ts');
assert.deepEqual(classifyDevice('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130.0.0.0 Safari/537.36'), { device: 'computer', os: 'Windows', browser: 'Chrome' });
assert.deepEqual(classifyDevice('Mozilla/5.0 (Linux; Android 13; K) AppleWebKit/537.36 Chrome/130.0.0.0 Mobile Safari/537.36'), { device: 'mobile', os: 'Android', browser: 'Chrome' });
assert.deepEqual(classifyDevice('Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1'), { device: 'mobile', os: 'iOS', browser: 'Safari' });
assert.equal(classifyDevice('Mozilla/5.0 (iPad; CPU OS 18_0 like Mac OS X) Version/18.0 Safari/604.1').device, 'tablet');
assert.equal(classifyDevice('Mozilla/5.0 (Linux; Android 13; K) Chrome/130.0.0.0 Safari/537.36').device, 'tablet');
assert.equal(classifyDevice('Mozilla/5.0 (Windows NT 10.0) Chrome/130.0 Safari/537.36 Edg/130.0').browser, 'Edge');
assert.equal(classifyDevice('Mozilla/5.0 (Android 13) Chrome/130.0 Mobile Safari/537.36 SamsungBrowser/24.0').browser, 'Samsung Internet');
assert.equal(classifyDevice('Mozilla/5.0 (iPhone) FxiOS/130.0 Mobile Safari/604.1').browser, 'Firefox');
assert.equal(classifyDevice('curl/8.0').device, 'bot');
assert.equal(classifyDevice(null).device, 'unknown');
assert.deepEqual(Object.keys(classifyDevice('anything')).sort(), ['browser', 'device', 'os']);
assert.equal(ipNumber('::ffff:198.51.100.2').value, ipNumber('198.51.100.2').value);
assert.equal(ipNumber('2001:db8::1').value, ipNumber('2001:0db8:0:0:0:0:0:1').value);
const ranges = parseRanges('198.51.100.0/25\n198.51.100.128/25\ninvalid\n0.0.0.0/0\n', 4);
assert.equal(ranges.length, 1);
assert.equal(contains(ranges, ipNumber('198.51.100.255').value), true);
assert.equal(contains(ranges, ipNumber('198.51.101.0').value), false);
const ranges6 = parseRanges('2001:db8::/32\n', 6);
assert.equal(contains(ranges6, ipNumber('2001:db8:ffff::1').value), true);
assert.equal(contains(ranges6, ipNumber('2001:db9::1').value), false);
const fakeFetch = async url => new Response(url.includes('vpn/ipv4') ? '198.51.100.0/24' : url.includes('vpn/ipv6') ? '2001:db8::/32' : url.includes('torbulk') ? '203.0.113.1\n' : JSON.stringify([{ exit_ip: '203.0.113.2', username: 'ignored', geolocation: { city: 'ignored' } }]));
const data = await fetchLists(fakeFetch);
assert.equal(classifyNetwork('198.51.100.5', data).vpn, true);
assert.equal(classifyNetwork('2001:db8::5', data).vpn, true);
assert.equal(classifyNetwork('::ffff:198.51.100.5', data).vpn, true);
assert.equal(classifyNetwork('203.0.113.1', data).tor, true);
assert.equal(classifyNetwork('203.0.113.2', data).proxy, true);
assert.equal(networkLabel(classifyNetwork('192.0.2.1', data)).label, 'Sem indícios nas listas');
const failed = await fetchLists(async () => new Response('down', { status: 503 }));
assert.equal(networkLabel(classifyNetwork('192.0.2.1', failed)).label, 'Não verificado');
assert.equal(networkLabel({ vpn: false, proxy: null, tor: false }).label, 'Verificação parcial');
assert.equal(networkLabel({ vpn: true, proxy: null, tor: null }).suspected, true);
assert.equal(deviceLabel({}).label, 'Não registrado');
assert.equal(deviceLabel({ device: 'mobile', os: 'Android', browser: 'Chrome' }).detail, 'Android · Chrome');
let writes = [], loads = 0;
const db = { rpc: async (name, args) => { writes.push({ name, args }); return { error: null }; } };
await enrichNetworks(db, [{ ip: '198.51.100.5' }, { ip: '198.51.100.5' }], async () => { loads++; return data; });
assert.equal(writes[0].args.p_records.length, 1);
assert.deepEqual(Object.keys(writes[0].args.p_records[0]).sort(), ['ip', 'proxy', 'tor', 'vpn']);
await enrichNetworks(db, [{ ip: '198.51.100.5', vpn: true, proxy: false, tor: false, network_checked_at: new Date().toISOString() }], async () => { loads++; return data; });
assert.equal(loads, 1);
await enrichNetworks(db, [{ ip: '198.51.100.5', vpn: null, proxy: false, tor: false, network_checked_at: new Date().toISOString() }], async () => { loads++; return data; });
assert.equal(loads, 2);
console.log('Passed: coarse device/browser classification, IPv4/IPv6 range boundaries, VPN/proxy/Tor positives, unknown and partial failures, deduplicated cached checks and minimal stored fields.');
