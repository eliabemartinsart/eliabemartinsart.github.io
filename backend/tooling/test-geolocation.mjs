import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';
import assert from 'node:assert/strict';
const { code } = await transform(await readFile('../supabase/functions/visit-report/geo.ts', 'utf8'), { loader: 'ts', format: 'esm' });
const { enrichLocation, enrichReport } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
let calls = [], requests = 0, claimed = true;
const db = { rpc: async (name, args) => { calls.push({ name, args }); return { data: name === 'claim_ip_location' ? claimed : null, error: null }; } };
const fakeFetch = async (url, options) => {
  requests++;
  assert.ok(url.startsWith('https://ipwho.is/198.51.100.1?'));
  assert.ok(url.includes('fields=success,city,region,country,country_code'));
  assert.equal(options.redirect, 'error');
  return new Response(JSON.stringify({ success: true, city: '<script>\u0000x</script>', region: 'Ceará', country: 'Brasil', country_code: 'BR', latitude: 1, longitude: 2 }));
};
await enrichLocation(db, '198.51.100.1', fakeFetch);
assert.equal(requests, 1);
assert.equal(calls.at(-1).args.p_city, '<script>x</script>');
assert.deepEqual(Object.keys(calls.at(-1).args).sort(), ['p_city', 'p_country', 'p_country_code', 'p_ip', 'p_region']);
assert.equal(calls.at(-1).args.p_region, 'Ceará');
claimed = false;
await enrichLocation(db, '198.51.100.1', fakeFetch);
assert.equal(requests, 1);
const beforeInvalid = calls.length;
await enrichLocation(db, 'https://example.com/secret', fakeFetch);
assert.equal(calls.length, beforeInvalid);
claimed = true;
await enrichLocation(db, '198.51.100.1', async () => { throw new Error('timeout'); });
assert.equal(calls.at(-1).name, 'finish_ip_location');
assert.equal(calls.at(-1).args.p_country, null);
await enrichLocation(db, '198.51.100.1', async () => new Response('rate limited', { status: 429 }));
assert.equal(calls.at(-1).args.p_city, null);
await enrichLocation(db, '198.51.100.1', async () => new Response('not json'));
assert.equal(calls.at(-1).args.p_country, null);
let active = 0, maximum = 0, total = 0;
await enrichReport(db, [...Array.from({ length: 12 }, (_, i) => ({ ip: `198.51.100.${i + 1}` })), { ip: '198.51.100.1' }], async () => {
  active++; total++; maximum = Math.max(maximum, active);
  await new Promise(resolve => setTimeout(resolve, 2)); active--;
  return new Response(JSON.stringify({ success: true, country: 'Brasil', country_code: 'BR' }));
});
assert.equal(total, 12);
assert.ok(maximum <= 5);
console.log('Passed: minimal geolocation fields, server cache claim, invalid IP rejection, timeout/rate-limit/malformed-response fallback, deduplication and bounded concurrency.');
